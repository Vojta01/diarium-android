import androidx.compose.ui.unit.TextUnit

/**
 * Drop-in replacement for `androidx.compose.material3.Text` that translates the Czech source
 * string into the selected UI language.
 *
 * Why a wrapper instead of `stringResource`: the app was written with Czech literals in place
 * (831 of them across 91 files). Moving every one to `strings.xml` would be a huge, risky
 * refactor. This wrapper keeps the Czech literal as the key and looks it up in [EnStrings];
 * a missing key falls back to the Czech text, so a forgotten string is visible but never
 * crashes or shows an empty label.
 *
 * Call sites only need their import changed:
 * `import androidx.compose.material3.Text` -> `import cz.digitalnivedomi.diarium.ui.i18n.Text`.
 */
@Composable
fun Text(
    text: String,
    modifier: Modifier = Modifier,
    color: Color = Color.Unspecified,
    fontSize: TextUnit = TextUnit.Unspecified,
    fontStyle: FontStyle? = null,
    fontWeight: FontWeight? = null,
    fontFamily: FontFamily? = null,
    letterSpacing: TextUnit = TextUnit.Unspecified,
    textDecoration: TextDecoration? = null,
    textAlign: TextAlign? = null,
    lineHeight: TextUnit = TextUnit.Unspecified,
    overflow: TextOverflow = TextOverflow.Clip,
    softWrap: Boolean = true,
    maxLines: Int = Int.MAX_VALUE,
    minLines: Int = 1,
    onTextLayout: (TextLayoutResult) -> Unit = {},
    style: TextStyle = LocalTextStyle.current,
) {
    MaterialText(
        text = translate(text),
        modifier = modifier,
        color = color,
        fontSize = fontSize,
        fontStyle = fontStyle,
        fontWeight = fontWeight,
        fontFamily = fontFamily,
        letterSpacing = letterSpacing,
        textDecoration = textDecoration,
        textAlign = textAlign,
        lineHeight = lineHeight,
        overflow = overflow,
        softWrap = softWrap,
        maxLines = maxLines,
        minLines = minLines,
        onTextLayout = onTextLayout,
        style = style,
    )
}

